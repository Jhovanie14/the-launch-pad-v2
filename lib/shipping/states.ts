const CODES = new Set(US_STATES.map((s) => s.code));

export function isKnownState(code: string): boolean {
  return CODES.has(code.trim().toUpperCase());
}

/** A state we ship to: one of the 50 states or DC, and not turned off by the owner. */
export function isShippableState(code: string, excluded: string[]): boolean {
  const c = (code ?? "").trim().toUpperCase();
  return CODES.has(c) && !excluded.map((e) => e.toUpperCase()).includes(c);
}
